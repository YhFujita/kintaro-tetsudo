  // 文字数の長い順にソート（部分一致による誤変換を防ぐ）
  const SORTED_DICT = RAW_DICTIONARY.slice().sort((a, b) => b[0].length - a[0].length);

  // 正規表現エスケープ
  function escapeRegExp(str) {
    return str.replace(/[.*+?^$${}()|[\]\\]/g, '\\$&');
  }

  // 一括置換用の正規表現を作成（すべて漢字のみのパターン）
  const DICT_MAP = new Map(SORTED_DICT);
  const DICT_REGEX = new RegExp(
    SORTED_DICT.map(item => escapeRegExp(item[0])).join('|'),
    'g'
  );

  const KANJI_CHAR_REGEX = /[\u4E00-\u9FFF\u3400-\u4DBF\uF900-\uFAFF]/g;

  /**
   * プレーンテキストにルビ（<ruby>）タグを付与する
   * 漢字の部分だけに厳密にルビを振り、ひらがな・カタカナ・記号・英数字には一切触れません。
   */
  function applyRubyToPlainText(text) {
    if (!text) return '';

    const placeholders = [];
    function makeRubyPlaceholder(kanji, yomi) {
      const idx = placeholders.length;
      placeholders.push(`<ruby>${kanji}<rt>${yomi}</rt></ruby>`);
      return `\x00RUBY_${idx}\x00`;
    }

    // 1. 既存の <ruby>...</ruby> タグをプレースホルダー化して保護（二重ルビ化を完全防止）
    let processed = String(text).replace(/<ruby>[\s\S]*?<\/ruby>/gi, match => {
      const idx = placeholders.length;
      placeholders.push(match);
      return `\x00RUBY_${idx}\x00`;
    });

    // 2. {漢字|よみ} の明示記法をプレースホルダー化
    processed = processed.replace(/\{([^|{}]+)\|([^|{}]+)\}/g, (_, kanji, yomi) => {
      return makeRubyPlaceholder(kanji, yomi);
    });

    // 3. 数字＋単位のルビ付け（即座にプレースホルダー化して保護）
    processed = processed
      .replace(/(\d+)億円/g, (_, n) => n + makeRubyPlaceholder('億', 'おく') + makeRubyPlaceholder('円', 'えん'))
      .replace(/(\d+)億/g, (_, n) => n + makeRubyPlaceholder('億', 'おく'))
      .replace(/(\d+)万円/g, (_, n) => n + makeRubyPlaceholder('万', 'まん') + makeRubyPlaceholder('円', 'えん'))
      .replace(/(\d+)万/g, (_, n) => n + makeRubyPlaceholder('万', 'まん'))
      .replace(/(\d+)円/g, (_, n) => n + makeRubyPlaceholder('円', 'えん'))
      .replace(/(\d+)年目/g, (_, n) => n + makeRubyPlaceholder('年目', 'ねんめ'))
      .replace(/(\d+)年/g, (_, n) => n + makeRubyPlaceholder('年', 'ねん'))
      .replace(/(\d+)月/g, (_, n) => n + makeRubyPlaceholder('月', 'がつ'))
      .replace(/(\d+)位/g, (_, n) => n + makeRubyPlaceholder('位', 'い'))
      .replace(/(\d+)人/g, (_, n) => n + makeRubyPlaceholder('人', 'にん'))
      .replace(/(\d+)個/g, (_, n) => n + makeRubyPlaceholder('個', 'こ'))
      .replace(/(\d+)枚/g, (_, n) => n + makeRubyPlaceholder('枚', 'まい'))
      .replace(/(\d+)件/g, (_, n) => n + makeRubyPlaceholder('件', 'けん'))
      .replace(/(\d+)回/g, (_, n) => n + makeRubyPlaceholder('回', 'かい'));

    // 4. 熟語辞書置換（長い順。すべて純粋な漢字熟語。置換結果もプレースホルダー化）
    const parts = processed.split(/(\x00RUBY_\d+\x00)/g);
    for (let i = 0; i < parts.length; i++) {
      if (!parts[i].startsWith('\x00RUBY_')) {
        parts[i] = parts[i].replace(DICT_REGEX, match => {
          const yomi = DICT_MAP.get(match);
          return yomi ? makeRubyPlaceholder(match, yomi) : match;
        });
      }
    }
    processed = parts.join('');

    // 5. 残った単漢字をフォールバック辞書で置換（漢字1文字だけに正確にルビを付与）
    const parts2 = processed.split(/(\x00RUBY_\d+\x00)/g);
    for (let i = 0; i < parts2.length; i++) {
      if (!parts2[i].startsWith('\x00RUBY_')) {
        parts2[i] = parts2[i].replace(KANJI_CHAR_REGEX, ch => {
          const yomi = SINGLE_KANJI_DICT[ch];
          return yomi ? makeRubyPlaceholder(ch, yomi) : ch;
        });
      }
    }
    processed = parts2.join('');

    // 6. すべてのプレースホルダーを復元（再帰的にプレースホルダーが残らなくなるまで復元）
    while (processed.includes('\x00RUBY_')) {
      processed = processed.replace(/\x00RUBY_(\d+)\x00/g, (_, idx) => placeholders[Number(idx)]);
    }
    return processed;
  }

  /**
   * HTMLタグを含む文字列に安全にルビを振る
   * ・<svg>...</svg>, <style>...</style>, <script>...</script> は内部も含めて完全に保護
   */
  function ruby(htmlOrText) {
    if (htmlOrText === null || htmlOrText === undefined) return '';
    let str = String(htmlOrText);

    // 1. SVG, STYLE, SCRIPT タグ全体をプレースホルダーに退避（内部の<text>等へのルビ混入を完全防止）
    const rawBlocks = [];
    str = str.replace(/<(svg|style|script)\b[\s\S]*?<\/\1>/gi, match => {
      const idx = rawBlocks.length;
      rawBlocks.push(match);
      return `\x00RAW_BLOCK_${idx}\x00`;
    });

    // 2. 既存の <ruby>...</ruby> または HTMLタグで分割し、通常テキスト部分のみ変換
    const tokens = str.split(/(<ruby>[\s\S]*?<\/ruby>|<[^>]+>)/g);
    let result = tokens
      .map(token => {
        if (token.startsWith('<') || token.startsWith('\x00RAW_BLOCK_')) return token;
        return applyRubyToPlainText(token);
      })
      .join('');

    // 3. 退避したタグ全体を完全復元
    result = result.replace(/\x00RAW_BLOCK_(\d+)\x00/g, (_, idx) => rawBlocks[Number(idx)]);
    return result;
  }

  /**
   * 金額（万円単位の数値）を桃鉄風の読みやすいルビ付き文字列に変換
   * 例: 1000 -> "1000万円", 12500 -> "1億2500万円", -500 -> "-500万円"
   */
  function formatMoney(manYen, withRuby = true) {
    const val = Math.round(Number(manYen) || 0);
    const isNeg = val < 0;
    const abs = Math.abs(val);
    const oku = Math.floor(abs / 10000);
    const man = abs % 10000;

    let result = '';
    if (oku > 0 && man > 0) {
      result = `${oku}億${man}万円`;
    } else if (oku > 0 && man === 0) {
      result = `${oku}億円`;
    } else {
      result = `${man}万円`;
    }
    if (isNeg) {
      result = `▲${result}`;
    }
    return withRuby ? ruby(result) : result;
  }

