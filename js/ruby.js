  // 文字数の長い順にソート（部分一致による誤変換を防ぐ）
  const SORTED_DICT = RAW_DICTIONARY.slice().sort((a, b) => b[0].length - a[0].length);

  // 正規表現エスケープ
  function escapeRegExp(str) {
    return str.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  }

  // 一括置換用の正規表現を作成
  const DICT_MAP = new Map(SORTED_DICT);
  const DICT_REGEX = new RegExp(
    SORTED_DICT.map(item => escapeRegExp(item[0])).join('|'),
    'g'
  );

  /**
   * プレーンテキストにルビ（<ruby>）タグを付与する
   * 1. {漢字|かんじ} の明示記法を変換
   * 2. 辞書に登録された漢字を自動変換
   */
  function applyRubyToPlainText(text) {
    if (!text) return '';
    // {漢字|よみ} 記法を先にプレースホルダー化
    const placeholders = [];
    let processed = String(text).replace(/\{([^|{}]+)\|([^|{}]+)\}/g, (_, kanji, yomi) => {
      const idx = placeholders.length;
      placeholders.push(`<ruby>${kanji}<rt>${yomi}</rt></ruby>`);
      return `\x00RUBY_${idx}\x00`;
    });

    // 数字＋単位（億・万円・年目・月・個・マス・位・人）の自然なルビ付け
    processed = processed
      .replace(/(\d+)億円/g, '$1<ruby>億円<rt>おくえん</rt></ruby>')
      .replace(/(\d+)億/g, '$1<ruby>億<rt>おく</rt></ruby>')
      .replace(/(\d+)万円/g, '$1<ruby>万円<rt>まんえん</rt></ruby>')
      .replace(/(\d+)年目/g, '$1<ruby>年目<rt>ねんめ</rt></ruby>')
      .replace(/(\d+)年/g, '$1<ruby>年<rt>ねん</rt></ruby>')
      .replace(/(\d+)月/g, '$1<ruby>月<rt>がつ</rt></ruby>')
      .replace(/(\d+)位/g, '$1<ruby>位<rt>い</rt></ruby>')
      .replace(/(\d+)人/g, '$1<ruby>人<rt>にん</rt></ruby>')
      .replace(/(\d+)個/g, '$1<ruby>個<rt>こ</rt></ruby>')
      .replace(/(\d+)枚/g, '$1<ruby>枚<rt>まい</rt></ruby>')
      .replace(/(\d+)件/g, '$1<ruby>件<rt>けん</rt></ruby>');

    // 辞書置換（既に<ruby>内にあるものは除外するため、タグ外テキストのみ対象）
    const parts = processed.split(/(<ruby>.*?<\/ruby>)/g);
    for (let i = 0; i < parts.length; i++) {
      if (!parts[i].startsWith('<ruby>')) {
        parts[i] = parts[i].replace(DICT_REGEX, match => {
          const yomi = DICT_MAP.get(match);
          return yomi ? `<ruby>${match}<rt>${yomi}</rt></ruby>` : match;
        });
      }
    }
    processed = parts.join('');

    // プレースホルダーを戻す
    processed = processed.replace(/\x00RUBY_(\d+)\x00/g, (_, idx) => placeholders[Number(idx)]);
    return processed;
  }

  /**
   * HTMLタグを含む可能性のある文字列に安全にルビを振る
   */
  function ruby(htmlOrText) {
    if (htmlOrText === null || htmlOrText === undefined) return '';
    const str = String(htmlOrText);
    // <ruby>...</ruby> または HTMLタグで分割し、テキスト部分のみ変換
    const tokens = str.split(/(<ruby>[\s\S]*?<\/ruby>|<[^>]+>)/g);
    return tokens
      .map(token => {
        if (token.startsWith('<')) return token;
        return applyRubyToPlainText(token);
      })
      .join('');
  }

  /**
   * 金額（万円単位の数値）を桃鉄風の読みやすいルビ付き文字列に変換
   * 例: 1000 -> "1000万円", 12500 -> "1億2500万円", -500 -> "-500万円"
   */
  function formatMoney(manYen, withRuby = true) {
    const val = Math.round(Number(manYen) || 0);
    const isNeg = val < 0;
    const abs = Math.abs(val);
    const oku = Math.floor(abs / 10000);
    const man = abs % 10000;

    let result = '';
    if (oku > 0 && man > 0) {
      result = `${oku}億${man}万円`;
    } else if (oku > 0 && man === 0) {
      result = `${oku}億円`;
    } else {
      result = `${man}万円`;
    }
    if (isNeg) {
      result = `▲${result}`;
    }
    return withRuby ? ruby(result) : result;
  }

  // フリガナ表示ON/OFFの切り替え
  let rubyEnabled = true;
  function toggleRuby(forceState) {
    rubyEnabled = typeof forceState === 'boolean' ? forceState : !rubyEnabled;
    document.body.classList.toggle('hide-ruby', !rubyEnabled);
    return rubyEnabled;
  }

