  let rubyEnabled = true;
  function toggleRuby(forceState) {
    rubyEnabled = typeof forceState === 'boolean' ? forceState : !rubyEnabled;
    document.body.classList.toggle('hide-ruby', !rubyEnabled);
    return rubyEnabled;
  }

  KT.ruby = ruby;
  KT.formatMoney = formatMoney;
  KT.toggleRuby = toggleRuby;
  KT.isRubyEnabled = () => rubyEnabled;
